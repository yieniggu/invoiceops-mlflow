"""Authentication against InvoiceOps (token and session introspection) with a short cache."""

from __future__ import annotations

import asyncio
import hashlib
import re
import time
from collections.abc import Awaitable, Callable
from dataclasses import dataclass, field
from typing import Any

import httpx

from .config import Settings

UUID_RE = re.compile(r"^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$")
WORKSPACE_RE = re.compile(
    r"^(?:org|grp)-[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$"
)
MAX_CACHE_ENTRIES = 20_000
# InvoiceOps API tokens: ``iop_`` plus 32 random bytes in base64url (43 characters). The gateway
# only asks InvoiceOps about credentials that look like one (cheap prefilter against floods of
# junk bearer values); the bounds are deliberately wider than the exact shape.
TOKEN_FORMAT_RE = re.compile(r"^iop_[A-Za-z0-9_-]{20,128}$")
# Gateway session tokens (``mls_`` + 32 random bytes in base64url) and one-time handoff codes (32
# random bytes in base64url), as generated by invoiceops-app/apps/backend/src/features/mlflow-sso.
# tests/test_credential_shapes.py pins both regexes to fixtures of the backend's real output.
SESSION_FORMAT_RE = re.compile(r"^mls_[A-Za-z0-9_-]{20,128}$")
CODE_FORMAT_RE = re.compile(r"^[A-Za-z0-9_-]{20,128}$")


def token_format_ok(secret: str) -> bool:
    return TOKEN_FORMAT_RE.fullmatch(secret) is not None


def session_format_ok(value: str) -> bool:
    return SESSION_FORMAT_RE.fullmatch(value) is not None


def code_format_ok(value: str) -> bool:
    return CODE_FORMAT_RE.fullmatch(value) is not None


class Throttled(Exception):
    """The caller's failure budget is spent: no backend call is made."""


class IntrospectionUnavailable(Exception):
    """InvoiceOps could not answer; the gateway fails closed and never caches this."""


def workspace_name(organization_id: str, group_id: str | None) -> str | None:
    """One workspace per organization context and one per group context.

    Names are derived only from validated UUIDs, so a caller can never smuggle a different
    workspace through a crafted identifier (MLflow limits names to 63 chars: ``org-`` and
    ``grp-`` plus a 36 char UUID is 40).
    """
    if not UUID_RE.match(organization_id):
        return None
    if group_id is None:
        return f"org-{organization_id}"
    if not UUID_RE.match(group_id):
        return None
    return f"grp-{group_id}"


@dataclass(frozen=True)
class Context:
    workspace: str
    organization_id: str
    group_id: str | None
    label: str


@dataclass(frozen=True)
class TokenIdentity:
    user_id: str
    scopes: frozenset[str]
    context: Context

    @property
    def can_read(self) -> bool:
        return bool(self.scopes & {"mlflow:read", "mlflow:write"})

    @property
    def can_write(self) -> bool:
        return "mlflow:write" in self.scopes


@dataclass(frozen=True)
class SessionIdentity:
    user_id: str
    contexts: tuple[Context, ...]


@dataclass
class _Entry:
    expires: float
    value: Any = field(default=None)


class _TTLCache:
    def __init__(self, clock: Callable[[], float]) -> None:
        self._clock = clock
        self._items: dict[str, _Entry] = {}

    def get(self, key: str) -> tuple[bool, Any]:
        entry = self._items.get(key)
        if entry is None:
            return False, None
        if entry.expires <= self._clock():
            del self._items[key]
            return False, None
        return True, entry.value

    def discard(self, key: str) -> None:
        self._items.pop(key, None)

    def put(self, key: str, value: Any, ttl: float) -> None:
        if ttl <= 0:
            return
        if len(self._items) >= MAX_CACHE_ENTRIES:
            now = self._clock()
            self._items = {k: e for k, e in self._items.items() if e.expires > now}
            if len(self._items) >= MAX_CACHE_ENTRIES:
                self._items.pop(next(iter(self._items)))
        self._items[key] = _Entry(self._clock() + ttl, value)


def _digest(kind: str, secret: str) -> str:
    return hashlib.sha256(f"{kind}:{secret}".encode()).hexdigest()


def _clamp(ttl: Any, maximum: int) -> int:
    if isinstance(ttl, bool) or not isinstance(ttl, int | float):
        return 0
    return max(0, min(int(ttl), maximum))


class Introspector:
    """Caches per SHA-256 of the credential; the raw secret is never stored or logged."""

    def __init__(
        self,
        settings: Settings,
        client: httpx.AsyncClient,
        clock: Callable[[], float] = time.monotonic,
    ) -> None:
        self._settings = settings
        self._client = client
        self._cache = _TTLCache(clock)
        self._inflight: dict[str, asyncio.Future[Any]] = {}

    async def _post(
        self, path: str, body: dict[str, str], *, empty_ok: bool = False
    ) -> dict[str, Any]:
        try:
            response = await self._client.post(
                f"{self._settings.introspection_url}{path}",
                json=body,
                headers={"Authorization": f"Bearer {self._settings.introspection_secret}"},
                timeout=httpx.Timeout(3.0, connect=2.0),
            )
        except httpx.HTTPError as error:
            raise IntrospectionUnavailable(type(error).__name__) from error
        if empty_ok and response.status_code == 204:
            return {}
        if response.status_code != 200:
            raise IntrospectionUnavailable(f"status {response.status_code}")
        try:
            data = response.json()
        except ValueError as error:
            raise IntrospectionUnavailable("invalid json") from error
        if not isinstance(data, dict):
            raise IntrospectionUnavailable("invalid payload")
        return data

    async def _cached(
        self,
        kind: str,
        secret: str,
        load: Callable[[], Awaitable[tuple[Any, int]]],
        gate: Callable[[], None] | None = None,
    ) -> Any:
        """Cached lookup. ``gate`` runs only on a cache miss, right before InvoiceOps is called;
        it may raise ``Throttled`` (no backend call, nothing cached)."""
        key = _digest(kind, secret)
        while True:
            hit, value = self._cache.get(key)
            if hit:
                return value
            pending = self._inflight.get(key)
            if pending is None:
                break
            try:
                return await asyncio.shield(pending)
            except Throttled:
                continue  # the leader was throttled, not this caller: ask again with its own gate
            except asyncio.CancelledError:
                # The leader was cancelled (its client went away): that says nothing about the
                # credential, so retry instead of failing every follower. When it is this
                # caller that is being cancelled, the cancellation propagates.
                if not pending.cancelled():
                    raise
        future: asyncio.Future[Any] = asyncio.get_running_loop().create_future()
        self._inflight[key] = future
        try:
            if gate is not None:
                gate()
            value, ttl = await load()
            self._cache.put(key, value, ttl)
            future.set_result(value)
            return value
        except asyncio.CancelledError:
            future.cancel()
            raise
        except BaseException as error:
            future.set_exception(error)
            future.exception()  # mark retrieved when nobody else awaits it
            raise
        finally:
            self._inflight.pop(key, None)

    async def token(
        self, token: str, gate: Callable[[], None] | None = None
    ) -> TokenIdentity | None:
        async def load() -> tuple[TokenIdentity | None, int]:
            data = await self._post("/internal/api-tokens/introspect", {"token": token})
            if data.get("active") is not True:
                return None, _clamp(
                    data.get("cacheTtlSeconds"), self._settings.cache_inactive_seconds
                )
            org, group = data.get("organizationId"), data.get("groupId")
            scopes = data.get("scopes")
            user = data.get("userId")
            workspace = (
                workspace_name(org, group)
                if isinstance(org, str) and (group is None or isinstance(group, str))
                else None
            )
            if workspace is None or not isinstance(user, str) or not isinstance(scopes, list):
                return None, 0  # malformed answer: deny, do not cache
            identity = TokenIdentity(
                user_id=user,
                scopes=frozenset(s for s in scopes if isinstance(s, str)),
                context=Context(workspace, org, group, workspace),
            )
            return identity, _clamp(
                data.get("cacheTtlSeconds"), self._settings.cache_active_seconds
            )

        return await self._cached("token", token, load, gate)

    async def session(
        self, session_token: str, gate: Callable[[], None] | None = None
    ) -> SessionIdentity | None:
        async def load() -> tuple[SessionIdentity | None, int]:
            data = await self._post(
                "/internal/sessions/introspect", {"sessionToken": session_token}
            )
            if data.get("active") is not True:
                return None, _clamp(
                    data.get("cacheTtlSeconds"), self._settings.cache_inactive_seconds
                )
            user, raw = data.get("userId"), data.get("contexts")
            if not isinstance(user, str) or not isinstance(raw, list):
                return None, 0
            contexts: list[Context] = []
            for item in raw:
                if not isinstance(item, dict):
                    continue
                org, group = item.get("organizationId"), item.get("groupId")
                if not isinstance(org, str) or not (group is None or isinstance(group, str)):
                    continue
                workspace = workspace_name(org, group)
                if workspace is None:
                    continue
                label = item.get("label") if isinstance(item.get("label"), str) else workspace
                contexts.append(Context(workspace, org, group, str(label)[:200]))
            if not contexts:
                return None, _clamp(
                    data.get("cacheTtlSeconds"), self._settings.cache_inactive_seconds
                )
            ttl = _clamp(data.get("cacheTtlSeconds"), self._settings.cache_active_seconds)
            return SessionIdentity(user, tuple(contexts)), ttl

        return await self._cached("session", session_token, load, gate)

    async def exchange(self, code: str) -> tuple[str, int] | None:
        """Trade a one-time handoff code for a child session token (never cached).

        ``None`` for any refusal (unknown, replayed, expired); the reason is never disclosed.
        """
        data = await self._post("/internal/sessions/exchange", {"code": code})
        if data.get("active") is not True:
            return None
        token, expires = data.get("sessionToken"), data.get("expiresInSeconds")
        if (
            not isinstance(token, str)
            or not 0 < len(token) <= 512
            or isinstance(expires, bool)
            or not isinstance(expires, int)
            or expires <= 0
        ):
            return None
        return token, expires

    def forget_session(self, session_token: str) -> None:
        """Evict any cached answer for this child session."""
        self._cache.discard(_digest("session", session_token))

    async def revoke(self, session_token: str) -> None:
        """Revoke the child session in InvoiceOps and forget any cached answer for it.

        The cache entry is evicted even when the call fails, so a retry never sees a stale
        "active" answer.
        """
        self.forget_session(session_token)
        try:
            await self._post(
                "/internal/sessions/revoke", {"sessionToken": session_token}, empty_ok=True
            )
        finally:
            self.forget_session(session_token)
